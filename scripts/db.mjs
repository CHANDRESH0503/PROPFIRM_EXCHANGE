#!/usr/bin/env node
// Database tasks against a hosted Supabase project, through the Supabase CLI.
//
//   pnpm db:status            list applied vs local migrations (drift check)
//   pnpm db:migrate           apply pending migrations
//   pnpm db:types             regenerate src/lib/supabase/database.types.ts
//   pnpm db:seed              load supabase/seed.sql (refused on production)
//
// Target: SUPABASE_DB_URL / SUPABASE_PROJECT_REF from .env.local (staging by default).
// Production needs APP_ENV=production in the shell plus --yes-production, so it never happens
// by accident (docs/SYSTEM_DESIGN.md §7: migrations go local → staging → production).
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

if (existsSync(".env.local")) process.loadEnvFile(".env.local");

const [command, ...flags] = process.argv.slice(2);
const dbUrl = process.env.SUPABASE_DB_URL;
const ref = process.env.SUPABASE_PROJECT_REF;
const isProd = process.env.APP_ENV === "production";

function fail(message) {
  console.error(`db: ${message}`);
  process.exit(1);
}

function requireUrl() {
  if (!dbUrl) fail("SUPABASE_DB_URL is not set (Supabase → Connect → Session pooler URI).");
  if (isProd && !flags.includes("--yes-production")) fail("APP_ENV=production: pass --yes-production to continue.");
  return dbUrl;
}

function cli(args, opts = {}) {
  const result = spawnSync("pnpm", ["exec", "supabase", ...args], { stdio: opts.capture ? ["ignore", "pipe", "inherit"] : "inherit", encoding: "utf8" });
  if (result.status !== 0) process.exit(result.status ?? 1);
  return result.stdout;
}

switch (command) {
  case "status":
    cli(["migration", "list", "--remote", requireUrl()]);
    break;
  case "push":
    // --yes: the CLI's consent prompt can't run non-interactively; consent is this command itself.
    cli(["db", "push", "--remote", requireUrl(), ...(flags.includes("--dry-run") ? ["--dry-run"] : ["--yes"])]);
    break;
  case "types": {
    if (!ref) fail("SUPABASE_PROJECT_REF is not set.");
    const out = cli(["gen", "types", "typescript", "--remote", ref, "--schema", "public"], { capture: true });
    const target = resolve("src/lib/supabase/database.types.ts");
    writeFileSync(target, `// Generated by \`pnpm db:types\` from project ${ref}. Do not edit by hand.\n${out}`);
    console.log(`db: wrote ${target}`);
    break;
  }
  case "seed": {
    if (isProd) fail("refusing to seed production.");
    const url = requireUrl();
    if (!existsSync("supabase/seed.sql")) fail("supabase/seed.sql not found.");
    execFileSync("psql", [url, "-v", "ON_ERROR_STOP=1", "-f", "supabase/seed.sql"], { stdio: "inherit" });
    break;
  }
  default:
    fail(`unknown command "${command ?? ""}". Use status | push | types | seed.`);
}
